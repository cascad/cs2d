/// Максимальная дальность полёта банки за её время жизни (мир. ед.), с учётом
/// воздушного затухания. Закрытая форма интеграла `∫₀ᵀ v₀·(1-d)^t dt`. Единый
/// источник для сервера (кламп точки броска) и клиента (подсветка «куда долетит»),
/// чтобы предсказание совпадало.
#[inline]
pub fn grenade_max_reach() -> f32 {
    let v0 = GRENADE_SPEED;
    let d = GRENADE_AIR_DRAG_PER_SEC;
    let t = GRENADE_TIMER;
    if d <= 0.0 {
        return v0 * t;
    }
    let r = 1.0 - d;
    v0 * (r.powf(t) - 1.0) / r.ln()
}

