pub const GRENADE_AIR_DRAG_PER_SEC: f32 = 0.06; // 6%/сек экспоненциально
pub const GRENADE_RESTITUTION: f32    = 0.5;    // упругость отражения
pub const GRENADE_BOUNCE_DAMPING: f32 = 0.70;   // доп. гашение на ударе
