// Пока идёт удар — заморожены и разворот, и ДВИЖЕНИЕ, и рывок: ровно на
// длительность взмаха (= длине клипа атаки на клиенте). Управление возвращается
// точно с концом анимации; следующий удар готов чуть позже (MELEE_COOLDOWN).
pub const ATTACK_FACING_LOCK: f32 = MELEE_SWING_TIME;

#[cfg(test)]
mod timing_invariants {
    //! Инварианты временных окон: анимация ↔ механика ↔ кулдауны. Если тюнинг
    //! констант их ломает — визуал разъедется с геймплеем (удары «без взмаха»,
    //! урон после конца клипа и т.п.). Тесты фиксируют контракт.
    use super::*;

    #[test]
    fn melee_windows_are_consistent() {
        // клип взмаха короче кулдауна: каждый удар успевает доиграть анимацию
        assert!(MELEE_SWING_TIME < MELEE_COOLDOWN);
        // урон прилетает ВНУТРИ взмаха (и после серверного grace-окна)
        assert!(MELEE_HIT_DELAY > MELEE_CD_GRACE as f64);
        assert!(MELEE_HIT_DELAY < MELEE_SWING_TIME as f64);
        // лок движения = длине клипа (управление возвращается с концом анимации)
        assert_eq!(ATTACK_FACING_LOCK, MELEE_SWING_TIME);
    }

    #[test]
    fn stun_windows_are_consistent() {
        assert!(STUN_SWING_TIME < STUN_COOLDOWN);
        assert!(STUN_HIT_DELAY > STUN_CD_GRACE as f64);
        assert!(STUN_HIT_DELAY < STUN_SWING_TIME as f64);
        assert_eq!(STUN_FACING_LOCK, STUN_SWING_TIME);
    }

    #[test]
    fn dash_and_npc_windows_are_consistent() {
        // рывок: клип растягивается на DASH_DURATION, кулдаун должен быть больше
        assert!(DASH_DURATION < DASH_COOLDOWN);
        // непись: клип атаки короче её кулдауна («опускает руки» между ударами)
        assert!(NPC_ATTACK_ANIM < NPC_ATTACK_COOLDOWN);
        // урон неписи прилетает внутри её замаха
        assert!(NPC_HIT_DELAY > 0.0 && NPC_HIT_DELAY < NPC_ATTACK_ANIM);
    }
}
